import open3d as o3d, numpy as np, os, sys, json
sys.path.insert(0,os.path.dirname(os.path.abspath(__file__)))
from limpa_nuvem import *
out=r"C:\Users\pc\Desktop\Gatinho_ENTREGA"
p=carregar("pc_before.ply"); n,d,s=objeto(p)
F=o3d.io.read_triangle_mesh(R+r"\result\Fused.ply"); lado=np.sign(np.median(np.asarray(F.vertices)@n+d))
m=(s*lado)>0.6; o=p.select_by_index(np.where(m)[0])
l=np.array(o.cluster_dbscan(eps=0.8,min_points=8)); c=np.bincount(l[l>=0]); O=o.select_by_index(np.where(l==np.argmax(c))[0])
O,_=O.remove_statistical_outlier(30,3.0)
P=np.asarray(O.points); N=np.asarray(O.normals); cen=P.mean(0)
print("pontos",len(P),"frac normais p/ fora",np.mean(((P-cen)*N).sum(1)>0))
o3d.io.write_point_cloud(os.path.join(out,"gatinho_nuvem_original_limpa.ply"),O)
import time; t=time.time()
mesh,den=o3d.geometry.TriangleMesh.create_from_point_cloud_poisson(O,depth=10,width=0,scale=1.1,linear_fit=True)
den=np.asarray(den); V=np.asarray(mesh.vertices); print("poisson",len(V),len(mesh.triangles),round(time.time()-t))
tr=o3d.geometry.KDTreeFlann(O)
dist=np.array([np.sqrt(tr.search_knn_vector_3d(v,1)[2][0]) for v in V])
print("dist ao ponto: p50 p95 p99",np.percentile(dist,[50,95,99]).round(3))
keep=(dist<0.35)&(den>np.quantile(den,0.01))
mesh.remove_vertices_by_mask(~keep); mesh.remove_degenerate_triangles(); mesh.remove_unreferenced_vertices()
tc,nt,_=mesh.cluster_connected_triangles(); tc=np.array(tc); nt=np.array(nt); print("componentes",sorted(nt)[-5:],len(nt))
mesh.remove_triangles_by_mask(nt[tc]<0.02*nt.max()); mesh.remove_unreferenced_vertices()
mesh.compute_vertex_normals()
o3d.io.write_triangle_mesh(os.path.join(out,"gatinho_malha_alta_resolucao.ply"),mesh)
print(mesh,"watertight",mesh.is_watertight(),mesh.get_axis_aligned_bounding_box().get_extent())
